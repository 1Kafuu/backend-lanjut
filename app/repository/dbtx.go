package repository

import (
	"context"
	"errors"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// Kode SQLSTATE PostgreSQL yang dikenali aplikasi.
// Daftar lengkap ada di dokumentasi "Error Codes".
const (
	codeUniqueViolation      = "23505"
	codeSerializationFailure = "40001"
	codeDeadlockDetected     = "40P01"
)

// DBTX adalah kemampuan minimum untuk menjalankan query.
// *pgxpool.Pool dan pgx.Tx memenuhinya, sehingga repository dapat
// berjalan di luar maupun di dalam transaction tanpa mengubah query.
type DBTX interface {
	Exec(ctx context.Context, sql string, arguments ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

func pgErrorCode(err error) string {
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) {
		return pgErr.Code
	}
	return ""
}
